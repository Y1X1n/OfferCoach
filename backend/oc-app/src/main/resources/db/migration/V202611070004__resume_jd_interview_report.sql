-- M1–M4：简历、JD、面试会话、答案反馈、报告、题库与 AI 调用日志。
-- 题库检索使用 PostgreSQL pg_trgm，避免在小规格 ECS 上额外部署 Milvus。

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE resume (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES app_user (id),
    title           VARCHAR(120) NOT NULL,
    source_type     VARCHAR(8) NOT NULL DEFAULT 'FILE' CHECK (source_type IN ('FILE', 'MANUAL')),
    file_key        TEXT,
    file_name       VARCHAR(255),
    mime_type       VARCHAR(100),
    file_size       BIGINT,
    sha256          CHAR(64),
    page_count      INT,
    parse_status    VARCHAR(16) NOT NULL DEFAULT 'PENDING'
                    CHECK (parse_status IN ('PENDING', 'PARSING', 'READY', 'FAILED')),
    parse_error     VARCHAR(64),
    raw_text        TEXT,
    structured_json JSONB,
    summary         TEXT,
    summary_hash    CHAR(64),
    is_default      BOOLEAN NOT NULL DEFAULT false,
    deleted_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (source_type = 'MANUAL' OR file_key IS NOT NULL)
);

COMMENT ON TABLE resume IS '简历；软删只置 deleted_at，进行中会话引用的简历不可删除';
COMMENT ON COLUMN resume.source_type IS 'FILE 上传文件 / MANUAL 手动粘贴';
COMMENT ON COLUMN resume.structured_json IS '结构化简历 JSON，字段约定见 docs/design/data-model.md §4';

CREATE INDEX idx_resume_user_time ON resume (user_id, created_at DESC) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_resume_file ON resume (user_id, sha256)
    WHERE deleted_at IS NULL AND sha256 IS NOT NULL;
CREATE UNIQUE INDEX uq_resume_default ON resume (user_id)
    WHERE is_default AND deleted_at IS NULL;

CREATE TABLE job_description (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES app_user (id),
    title           VARCHAR(160),
    company         VARCHAR(160),
    raw_text        TEXT NOT NULL,
    structured_json JSONB,
    match_score     NUMERIC(5, 2),
    match_report    JSONB,
    content_hash    CHAR(64) NOT NULL,
    deleted_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_jd_user_time ON job_description (user_id, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX idx_jd_content_hash ON job_description (user_id, content_hash) WHERE deleted_at IS NULL;

CREATE TABLE interview_session (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES app_user (id),
    resume_id        BIGINT NOT NULL REFERENCES resume (id),
    jd_id            BIGINT NOT NULL REFERENCES job_description (id),
    status           VARCHAR(24) NOT NULL DEFAULT 'CREATED'
                     CHECK (status IN ('CREATED', 'PREPARING', 'READY', 'IN_PROGRESS',
                                       'PAUSED', 'FINISHED', 'REPORT_GENERATING',
                                       'REPORT_FAILED', 'COMPLETED', 'FAILED', 'ABANDONED')),
    config           JSONB NOT NULL,
    question_count   SMALLINT NOT NULL,
    answered_count   SMALLINT NOT NULL DEFAULT 0,
    current_seq      SMALLINT NOT NULL DEFAULT 1,
    total_score      NUMERIC(4, 1) CHECK (total_score BETWEEN 0 AND 100),
    failure_reason   VARCHAR(64),
    idempotency_key  VARCHAR(128) NOT NULL,
    started_at       TIMESTAMPTZ,
    finished_at      TIMESTAMPTZ,
    last_active_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at       TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, idempotency_key)
);

COMMENT ON TABLE interview_session IS '面试会话；同一用户同时最多一个未结束会话';

CREATE INDEX idx_session_user_time ON interview_session (user_id, created_at DESC);
CREATE INDEX idx_session_status ON interview_session (status);
CREATE UNIQUE INDEX uq_session_active ON interview_session (user_id)
    WHERE status IN ('CREATED', 'PREPARING', 'READY', 'IN_PROGRESS', 'PAUSED');

CREATE TABLE interview_question (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id         BIGINT NOT NULL REFERENCES interview_session (id) ON DELETE CASCADE,
    seq                SMALLINT NOT NULL,
    dimension          VARCHAR(24) NOT NULL
                       CHECK (dimension IN ('DEPTH', 'PROJECT', 'BEHAVIOR', 'FIT')),
    difficulty         VARCHAR(8) NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    question_text      TEXT NOT NULL,
    source             VARCHAR(16) NOT NULL
                       CHECK (source IN ('BANK', 'GENERATED', 'FOLLOW_UP')),
    bank_question_id   BIGINT,
    parent_question_id BIGINT REFERENCES interview_question (id),
    reference_points   JSONB NOT NULL DEFAULT '[]'::jsonb,
    context_json       JSONB NOT NULL DEFAULT '{}'::jsonb,
    why_this_question  TEXT,
    retrieval_json     JSONB NOT NULL DEFAULT '{}'::jsonb,
    status             VARCHAR(16) NOT NULL DEFAULT 'PENDING'
                       CHECK (status IN ('PENDING', 'ASKED', 'ANSWERED', 'SKIPPED')),
    asked_at           TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (session_id, seq)
);

CREATE TABLE interview_answer (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id        BIGINT NOT NULL REFERENCES interview_session (id) ON DELETE CASCADE,
    question_id       BIGINT NOT NULL UNIQUE REFERENCES interview_question (id),
    user_id           BIGINT NOT NULL REFERENCES app_user (id),
    input_mode        VARCHAR(8) NOT NULL CHECK (input_mode IN ('TEXT', 'VOICE')),
    answer_text       TEXT,
    audio_key         TEXT,
    audio_duration_ms INT,
    asr_status        VARCHAR(16) CHECK (asr_status IN ('NONE', 'PENDING', 'DONE', 'FAILED')),
    asr_confidence    NUMERIC(4, 3),
    word_count        INT,
    content_hash      CHAR(64),
    duration_ms       INT,
    status            VARCHAR(16) NOT NULL DEFAULT 'PENDING'
                      CHECK (status IN ('PENDING', 'SCORING', 'SCORED', 'FAILED', 'REJECTED')),
    submitted_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_answer_session ON interview_answer (session_id, submitted_at);
CREATE INDEX idx_answer_user_time ON interview_answer (user_id, submitted_at DESC);

CREATE TABLE answer_feedback (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer_id         BIGINT NOT NULL REFERENCES interview_answer (id),
    version           SMALLINT NOT NULL DEFAULT 1,
    request_id        VARCHAR(64) NOT NULL,
    session_id        BIGINT NOT NULL REFERENCES interview_session (id),
    user_id           BIGINT NOT NULL REFERENCES app_user (id),
    overall_score     NUMERIC(3, 1) NOT NULL CHECK (overall_score BETWEEN 0 AND 10),
    dimensions        JSONB NOT NULL,
    strengths         JSONB NOT NULL DEFAULT '[]'::jsonb,
    improvements      JSONB NOT NULL DEFAULT '[]'::jsonb,
    evidence          JSONB NOT NULL DEFAULT '[]'::jsonb,
    rewritten_answer  TEXT,
    model             VARCHAR(64) NOT NULL,
    provider          VARCHAR(32) NOT NULL,
    prompt_version_id BIGINT,
    degraded          BOOLEAN NOT NULL DEFAULT false,
    tokens_in         INT,
    tokens_out        INT,
    first_token_ms    INT,
    latency_ms        INT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (request_id),
    UNIQUE (answer_id, version)
);

CREATE INDEX idx_feedback_session ON answer_feedback (session_id);
CREATE INDEX idx_feedback_answer ON answer_feedback (answer_id, version DESC);

CREATE TABLE interview_report (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id         BIGINT NOT NULL UNIQUE REFERENCES interview_session (id),
    user_id            BIGINT NOT NULL REFERENCES app_user (id),
    status             VARCHAR(16) NOT NULL DEFAULT 'GENERATING'
                       CHECK (status IN ('GENERATING', 'READY', 'FAILED')),
    overall_score      NUMERIC(4, 1) CHECK (overall_score BETWEEN 0 AND 100),
    radar              JSONB,
    summary            TEXT,
    highlights         JSONB NOT NULL DEFAULT '[]'::jsonb,
    risks              JSONB NOT NULL DEFAULT '[]'::jsonb,
    improvement_plan   JSONB NOT NULL DEFAULT '[]'::jsonb,
    question_breakdown JSONB NOT NULL DEFAULT '[]'::jsonb,
    attempts           SMALLINT NOT NULL DEFAULT 0,
    last_error         VARCHAR(64),
    generated_at       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_report_user_time ON interview_report (user_id, created_at DESC);
CREATE INDEX idx_report_pending ON interview_report (status, updated_at) WHERE status = 'GENERATING';

CREATE TABLE question_bank (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(200) NOT NULL,
    job_family        VARCHAR(64) NOT NULL,
    dimension         VARCHAR(24) NOT NULL
                      CHECK (dimension IN ('DEPTH', 'PROJECT', 'BEHAVIOR', 'FIT')),
    difficulty        VARCHAR(8) NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    tags              TEXT[] NOT NULL DEFAULT '{}',
    stem              TEXT NOT NULL,
    reference_answer  TEXT,
    scoring_points    JSONB NOT NULL DEFAULT '[]'::jsonb,
    source            VARCHAR(24) NOT NULL DEFAULT 'MANUAL'
                      CHECK (source IN ('MANUAL', 'IMPORT', 'GENERATED', 'PARTNER')),
    source_repo       VARCHAR(160),
    source_path       TEXT,
    source_url        TEXT,
    source_license    VARCHAR(64),
    company           VARCHAR(120),
    language          VARCHAR(16) NOT NULL DEFAULT 'zh-CN',
    status            VARCHAR(16) NOT NULL DEFAULT 'PUBLISHED'
                      CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    quality_score     NUMERIC(3, 2),
    embedding_status  VARCHAR(16) NOT NULL DEFAULT 'READY'
                      CHECK (embedding_status IN ('PENDING', 'INDEXING', 'READY', 'FAILED')),
    created_by        BIGINT REFERENCES app_user (id),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_repo, source_path)
);

COMMENT ON TABLE question_bank IS '题库；repo 导入以 (source_repo, source_path) 幂等';

CREATE INDEX idx_question_filter ON question_bank (status, job_family, dimension, difficulty);
CREATE INDEX idx_question_tags ON question_bank USING GIN (tags);
CREATE INDEX idx_question_stem_trgm ON question_bank USING GIN (stem gin_trgm_ops);
CREATE INDEX idx_question_title_trgm ON question_bank USING GIN (title gin_trgm_ops);
CREATE INDEX idx_question_company ON question_bank (company) WHERE company IS NOT NULL;

CREATE TABLE question_import_batch (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_repo      VARCHAR(160) NOT NULL,
    total_count      INT NOT NULL DEFAULT 0,
    success_count    INT NOT NULL DEFAULT 0,
    failed_count     INT NOT NULL DEFAULT 0,
    skipped_count    INT NOT NULL DEFAULT 0,
    status           VARCHAR(16) NOT NULL DEFAULT 'PENDING'
                     CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED')),
    error_report     JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_by       BIGINT REFERENCES app_user (id),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at      TIMESTAMPTZ
);

CREATE TABLE ai_call_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT,
    scene         VARCHAR(32) NOT NULL,
    provider      VARCHAR(32) NOT NULL,
    model         VARCHAR(64) NOT NULL,
    status        VARCHAR(16) NOT NULL CHECK (status IN ('SUCCESS', 'FAILED', 'DEGRADED')),
    tokens_in     INT,
    tokens_out    INT,
    first_token_ms INT,
    latency_ms    INT,
    error_code    VARCHAR(64),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_ai_call_time ON ai_call_log (created_at DESC);
CREATE INDEX idx_ai_call_scene ON ai_call_log (scene, created_at DESC);