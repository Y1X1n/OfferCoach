-- 支付对账与异常兜底。
-- 背景：关单失败、回调金额不符、已支付订单被本地关闭、发放通知重试耗尽等场景此前只写一行 WARN，
-- 资金已发生但权益未发放且无人跟进。本迁移把这类「需要人工介入」的事实持久化，并允许通知进入终态 DEAD。

ALTER TABLE payment_order DROP CONSTRAINT IF EXISTS payment_order_notify_status_check;
ALTER TABLE payment_order ADD CONSTRAINT payment_order_notify_status_check
    CHECK (notify_status IN ('PENDING', 'NOTIFIED', 'FAILED', 'DEAD'));

COMMENT ON COLUMN payment_order.notify_status IS
    '额度发放通知状态：PENDING 待发 / NOTIFIED 已发 / FAILED 失败待重试 / DEAD 重试耗尽或永久拒绝';

CREATE TABLE payment_exception (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no        VARCHAR(40),
    user_id         BIGINT,
    kind            VARCHAR(40) NOT NULL,
    detail          VARCHAR(500),
    amount_cents    INT,
    channel         VARCHAR(16),
    provider_txn_id VARCHAR(64),
    status          VARCHAR(16) NOT NULL DEFAULT 'OPEN'
                    CHECK (status IN ('OPEN', 'RESOLVED', 'IGNORED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at     TIMESTAMPTZ,
    UNIQUE (order_no, kind)
);

COMMENT ON TABLE payment_exception IS
    '支付异常人工处理队列：资金已发生但权益或状态无法自动收敛时写入，OPEN 表示待人工跟进';
COMMENT ON COLUMN payment_exception.kind IS
    'PAID_ON_INACTIVE_ORDER 已付款但订单非待支付 / AMOUNT_MISMATCH 金额不符 / CHANNEL_MISMATCH 渠道不符 / UNKNOWN_ORDER 未知订单 / CLOSE_UNCERTAIN 无法确认关单 / ENTITLEMENT_REJECTED 发放被永久拒绝 / ENTITLEMENT_DEAD 发放重试耗尽';
COMMENT ON COLUMN payment_exception.status IS 'OPEN 待处理 / RESOLVED 已处理 / IGNORED 已忽略';

CREATE INDEX idx_payment_exception_open ON payment_exception (status, created_at) WHERE status = 'OPEN';
