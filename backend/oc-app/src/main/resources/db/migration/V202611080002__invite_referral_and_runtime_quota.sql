-- 邀请注册、推荐奖励、运行时额度策略与注册风控。
-- 邀请码是可选项；注册开关、每日额度与奖励额度由管理端在线调整。

ALTER TABLE app_user ADD COLUMN IF NOT EXISTS invite_code VARCHAR(16);
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS referred_by BIGINT REFERENCES app_user (id);
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS signup_ip VARCHAR(64);
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS signup_device_hash CHAR(64);
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS allow_raw_resume_to_llm BOOLEAN NOT NULL DEFAULT true;

UPDATE app_user
SET invite_code = upper(substr(md5(id::text || clock_timestamp()::text), 1, 12))
WHERE invite_code IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_app_user_invite_code
    ON app_user (invite_code) WHERE invite_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_app_user_referred_by ON app_user (referred_by);

CREATE TABLE IF NOT EXISTS invite_reward (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inviter_id               BIGINT NOT NULL REFERENCES app_user (id),
    invitee_id               BIGINT NOT NULL UNIQUE REFERENCES app_user (id),
    inviter_interview_credits INT NOT NULL DEFAULT 0,
    invitee_resume_credits     INT NOT NULL DEFAULT 0,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_invite_reward_inviter_time
    ON invite_reward (inviter_id, created_at DESC);

CREATE TABLE IF NOT EXISTS platform_settings (
    id                            SMALLINT PRIMARY KEY CHECK (id = 1),
    registration_open             BOOLEAN NOT NULL DEFAULT true,
    daily_interview_limit         INT NOT NULL DEFAULT 3 CHECK (daily_interview_limit >= 0),
    daily_resume_limit            INT NOT NULL DEFAULT 3 CHECK (daily_resume_limit >= 0),
    free_monthly_interviews       INT NOT NULL DEFAULT 3 CHECK (free_monthly_interviews >= 0),
    free_monthly_resumes          INT NOT NULL DEFAULT 3 CHECK (free_monthly_resumes >= 0),
    invite_reward_inviter_interview INT NOT NULL DEFAULT 1 CHECK (invite_reward_inviter_interview >= 0),
    invite_reward_invitee_resume    INT NOT NULL DEFAULT 1 CHECK (invite_reward_invitee_resume >= 0),
    invite_daily_cap              INT NOT NULL DEFAULT 3 CHECK (invite_daily_cap >= 0),
    invite_total_cap              INT NOT NULL DEFAULT 20 CHECK (invite_total_cap >= 0),
    registration_ip_daily_cap     INT NOT NULL DEFAULT 20 CHECK (registration_ip_daily_cap >= 0),
    registration_device_daily_cap INT NOT NULL DEFAULT 3 CHECK (registration_device_daily_cap >= 0),
    updated_by                    BIGINT REFERENCES app_user (id),
    updated_at                    TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO platform_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

COMMENT ON TABLE platform_settings IS '单行运行时策略：注册开关、每日额度、邀请奖励与注册风控阈值';
COMMENT ON COLUMN app_user.invite_code IS '用户个人邀请码；注册时可作为可选推荐码';
COMMENT ON COLUMN app_user.referred_by IS '邀请人 user_id；仅注册时写入';
COMMENT ON COLUMN app_user.signup_device_hash IS '注册设备指纹 SHA-256，用于防止同设备批量注册与自推荐';