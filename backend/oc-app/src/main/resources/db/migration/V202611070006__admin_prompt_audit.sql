CREATE TABLE prompt_template (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL,
    scene       VARCHAR(32) NOT NULL,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE prompt_template IS 'Prompt 模板；code 为稳定标识，版本内容不可变';

CREATE TABLE prompt_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id       BIGINT NOT NULL REFERENCES prompt_template (id),
    version           VARCHAR(16) NOT NULL,
    content           TEXT NOT NULL,
    variables_schema  JSONB NOT NULL DEFAULT '{}'::jsonb,
    model_config      JSONB NOT NULL DEFAULT '{}'::jsonb,
    status            VARCHAR(16) NOT NULL DEFAULT 'DRAFT'
                      CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    content_hash      CHAR(64) NOT NULL,
    eval_report       JSONB,
    created_by        BIGINT REFERENCES app_user (id),
    published_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (template_id, version)
);

CREATE INDEX idx_prompt_version_active ON prompt_version (template_id, status);
CREATE UNIQUE INDEX uq_prompt_version_published
    ON prompt_version (template_id) WHERE status = 'PUBLISHED';

CREATE TABLE ab_experiment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id     BIGINT NOT NULL REFERENCES prompt_template (id),
    name            VARCHAR(120) NOT NULL,
    status          VARCHAR(16) NOT NULL DEFAULT 'DRAFT'
                    CHECK (status IN ('DRAFT', 'RUNNING', 'PAUSED', 'COMPLETED', 'ROLLED_BACK')),
    traffic_percent SMALLINT NOT NULL DEFAULT 10 CHECK (traffic_percent BETWEEN 0 AND 100),
    variants        JSONB NOT NULL DEFAULT '[]'::jsonb,
    guardrails      JSONB NOT NULL DEFAULT '{}'::jsonb,
    start_at        TIMESTAMPTZ,
    end_at          TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE ab_assignment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id BIGINT NOT NULL REFERENCES ab_experiment (id),
    user_id       BIGINT NOT NULL REFERENCES app_user (id),
    variant_key   VARCHAR(16) NOT NULL,
    assigned_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (experiment_id, user_id)
);

CREATE TABLE admin_audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id BIGINT NOT NULL REFERENCES app_user (id),
    action        VARCHAR(64) NOT NULL,
    target_type   VARCHAR(32) NOT NULL,
    target_id     VARCHAR(64),
    before_json   JSONB,
    after_json    JSONB,
    ip            VARCHAR(64),
    request_id    VARCHAR(64),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_admin_audit_time ON admin_audit_log (created_at DESC);
CREATE INDEX idx_admin_audit_admin ON admin_audit_log (admin_user_id, created_at DESC);

