CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE app_user (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              CITEXT UNIQUE,
    phone              VARCHAR(512),
    phone_hash         CHAR(64) UNIQUE,
    password_hash      VARCHAR(255) NOT NULL,
    nickname           VARCHAR(40) NOT NULL,
    avatar_url         TEXT,
    role               VARCHAR(16) NOT NULL DEFAULT 'USER'
                       CHECK (role IN ('USER', 'SUPPORT', 'ADMIN')),
    status             VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
                       CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED', 'DELETED')),
    timezone           VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai',
    email_verified_at  TIMESTAMPTZ,
    last_login_at      TIMESTAMPTZ,
    failed_login_count SMALLINT NOT NULL DEFAULT 0,
    locked_until       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at         TIMESTAMPTZ,
    CHECK (email IS NOT NULL OR phone_hash IS NOT NULL)
);

COMMENT ON TABLE app_user IS '账号主表；软删只置 deleted_at';
COMMENT ON COLUMN app_user.email IS '登录邮箱，CITEXT 大小写不敏感';
COMMENT ON COLUMN app_user.phone IS 'AES-GCM 密文 Base64，不存明文';
COMMENT ON COLUMN app_user.role IS 'USER 普通用户 / SUPPORT 客服 / ADMIN 管理员';
COMMENT ON COLUMN app_user.status IS 'ACTIVE 正常 / LOCKED 临时锁定 / DISABLED 停用 / DELETED 已注销';

CREATE INDEX idx_user_status ON app_user (status) WHERE deleted_at IS NULL;

CREATE TABLE user_quota (
    user_id             BIGINT PRIMARY KEY REFERENCES app_user (id),
    plan_code           VARCHAR(32) NOT NULL DEFAULT 'FREE',
    interview_credits   INT NOT NULL DEFAULT 0 CHECK (interview_credits >= 0),
    resume_credits      INT NOT NULL DEFAULT 0 CHECK (resume_credits >= 0),
    period_start        DATE,
    period_end          DATE,
    daily_session_date  DATE,
    daily_session_count INT NOT NULL DEFAULT 0 CHECK (daily_session_count >= 0),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    version             INT NOT NULL DEFAULT 0
);

COMMENT ON TABLE user_quota IS '额度余额快照；事实源是 quota_ledger，扣减时 SELECT FOR UPDATE';
COMMENT ON COLUMN user_quota.plan_code IS '当前生效套餐编码，引用 subscription_plan.code';
COMMENT ON COLUMN user_quota.interview_credits IS '面试次数余额，不得为负';
COMMENT ON COLUMN user_quota.resume_credits IS '简历解析次数余额，不得为负';
COMMENT ON COLUMN user_quota.daily_session_date IS '每日会话计数所属日期，跨日重置';

CREATE TABLE quota_ledger (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES app_user (id),
    quota_type      VARCHAR(16) NOT NULL CHECK (quota_type IN ('INTERVIEW', 'RESUME')),
    delta           INT NOT NULL CHECK (delta <> 0),
    balance_after   INT NOT NULL CHECK (balance_after >= 0),
    reason          VARCHAR(32) NOT NULL,
    ref_type        VARCHAR(24),
    ref_id          BIGINT,
    idempotency_key VARCHAR(128) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, idempotency_key)
);

COMMENT ON TABLE quota_ledger IS '额度流水，append-only；唯一键保证幂等';
COMMENT ON COLUMN quota_ledger.quota_type IS 'INTERVIEW 面试 / RESUME 简历解析';
COMMENT ON COLUMN quota_ledger.delta IS '正数增加、负数扣减，不得为 0';
COMMENT ON COLUMN quota_ledger.reason IS 'SESSION_CHARGE / SESSION_REFUND / PARSE_CHARGE / PARSE_REFUND / ADMIN_COMPENSATION';
COMMENT ON COLUMN quota_ledger.idempotency_key IS '调用方幂等键，同一用户内唯一';

CREATE INDEX idx_quota_ledger_user_time ON quota_ledger (user_id, created_at DESC);

CREATE TABLE subscription_plan (
    code              VARCHAR(32) PRIMARY KEY,
    name              VARCHAR(64) NOT NULL,
    price_cents       INT NOT NULL CHECK (price_cents >= 0),
    period_days       INT NOT NULL,
    interview_credits INT NOT NULL,
    resume_credits    INT NOT NULL,
    features          JSONB NOT NULL DEFAULT '{}'::jsonb,
    active            BOOLEAN NOT NULL DEFAULT true
);

COMMENT ON TABLE subscription_plan IS '套餐配置；前端可缓存 5 分钟';
COMMENT ON COLUMN subscription_plan.price_cents IS '价格，单位分';
COMMENT ON COLUMN subscription_plan.features IS '能力开关 JSON，整体读取';

CREATE TABLE user_subscription (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user (id),
    plan_code  VARCHAR(32) NOT NULL REFERENCES subscription_plan (code),
    status     VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE', 'EXPIRED', 'CANCELED')),
    started_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    auto_renew BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (expires_at > started_at)
);

COMMENT ON TABLE user_subscription IS '订阅记录；同一用户仅一条 ACTIVE';

CREATE UNIQUE INDEX uq_user_active_subscription
    ON user_subscription (user_id) WHERE status = 'ACTIVE';