-- 支付域：订单、退款、额度发放记录与回调审计。
-- 支付表由 oc-pay-service 独占写入（订单/退款/回调日志），oc-app 只经 oc-pay 内部接口读写订单；
-- payment_entitlement 由 oc-app 在支付成功后写入，唯一 order_no 保证额度只发放一次。

CREATE TABLE payment_order (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no        VARCHAR(40) NOT NULL UNIQUE,
    user_id         BIGINT NOT NULL REFERENCES app_user (id),
    plan_code       VARCHAR(32) NOT NULL,
    subject         VARCHAR(128) NOT NULL,
    amount_cents    INT NOT NULL CHECK (amount_cents > 0),
    currency        CHAR(3) NOT NULL DEFAULT 'CNY',
    channel         VARCHAR(16) NOT NULL CHECK (channel IN ('WECHAT', 'ALIPAY', 'MOCK')),
    channel_method  VARCHAR(16) NOT NULL DEFAULT 'QR',
    status          VARCHAR(16) NOT NULL DEFAULT 'CREATED'
                    CHECK (status IN ('CREATED', 'PAID', 'FAILED', 'REFUNDED', 'CLOSED')),
    provider_txn_id VARCHAR(64),
    prepay_id       TEXT,
    code_url        TEXT,
    client_ip       VARCHAR(64),
    idempotency_key VARCHAR(128) NOT NULL,
    notify_status   VARCHAR(16) NOT NULL DEFAULT 'PENDING'
                    CHECK (notify_status IN ('PENDING', 'NOTIFIED', 'FAILED')),
    notify_attempts INT NOT NULL DEFAULT 0 CHECK (notify_attempts >= 0),
    refunded_cents  INT NOT NULL DEFAULT 0 CHECK (refunded_cents >= 0),
    expires_at      TIMESTAMPTZ NOT NULL,
    paid_at         TIMESTAMPTZ,
    closed_at       TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, idempotency_key)
);

COMMENT ON TABLE payment_order IS '支付订单；由 oc-pay-service 独占写入，事实源为渠道流水 + 本表状态';
COMMENT ON COLUMN payment_order.order_no IS '业务订单号，形如 OC+yyyyMMddHHmmss+随机';
COMMENT ON COLUMN payment_order.plan_code IS '目标套餐编码，引用 subscription_plan.code';
COMMENT ON COLUMN payment_order.channel IS 'WECHAT 微信 / ALIPAY 支付宝 / MOCK 本地模拟';
COMMENT ON COLUMN payment_order.status IS 'CREATED 待支付 / PAID 已支付 / FAILED 失败 / REFUNDED 已退款 / CLOSED 已关闭';
COMMENT ON COLUMN payment_order.provider_txn_id IS '渠道交易号，用于对账';
COMMENT ON COLUMN payment_order.notify_status IS '额度发放通知状态：PENDING 待发 / NOTIFIED 已发 / FAILED 失败待重试';
COMMENT ON COLUMN payment_order.idempotency_key IS '下单幂等键，同一用户内唯一';

CREATE INDEX idx_payment_order_user_time ON payment_order (user_id, created_at DESC);
CREATE INDEX idx_payment_order_status_expire ON payment_order (status, expires_at);
CREATE UNIQUE INDEX uq_payment_order_provider_txn ON payment_order (provider_txn_id) WHERE provider_txn_id IS NOT NULL;

CREATE TABLE payment_refund (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_no         VARCHAR(40) NOT NULL UNIQUE,
    order_no          VARCHAR(40) NOT NULL REFERENCES payment_order (order_no),
    user_id           BIGINT NOT NULL REFERENCES app_user (id),
    amount_cents      INT NOT NULL CHECK (amount_cents > 0),
    status            VARCHAR(16) NOT NULL DEFAULT 'CREATED'
                      CHECK (status IN ('CREATED', 'SUCCESS', 'FAILED')),
    channel_refund_id VARCHAR(64),
    reason            VARCHAR(128),
    idempotency_key   VARCHAR(128) NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (order_no, idempotency_key)
);

COMMENT ON TABLE payment_refund IS '退款记录；同一订单内幂等键唯一，防止重复退款';
COMMENT ON COLUMN payment_refund.status IS 'CREATED 已受理 / SUCCESS 成功 / FAILED 失败';
COMMENT ON COLUMN payment_refund.idempotency_key IS '退款幂等键，同一订单内唯一';

CREATE INDEX idx_payment_refund_order ON payment_refund (order_no, created_at DESC);

CREATE TABLE payment_entitlement (
    order_no     VARCHAR(40) PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES app_user (id),
    plan_code    VARCHAR(32) NOT NULL,
    amount_cents INT NOT NULL CHECK (amount_cents > 0),
    applied_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE payment_entitlement IS '支付成功后的套餐发放记录；order_no 主键保证额度只发放一次（幂等）';
COMMENT ON COLUMN payment_entitlement.order_no IS '对应 payment_order.order_no';

CREATE TABLE payment_notify_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no        VARCHAR(40),
    channel         VARCHAR(16) NOT NULL,
    event_type      VARCHAR(64),
    provider_txn_id VARCHAR(64),
    signature_valid BOOLEAN NOT NULL,
    processed       BOOLEAN NOT NULL,
    message         VARCHAR(200),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE payment_notify_log IS '回调审计：只记录归一化结果，不存原始报文与任何凭据';
COMMENT ON COLUMN payment_notify_log.signature_valid IS '回调验签是否通过；未通过也会留痕';

CREATE INDEX idx_payment_notify_order ON payment_notify_log (order_no, created_at DESC);
